"""Streaming Excel exporter for the Power-System Dataset Generator."""

from __future__ import annotations

import math
import os
from pathlib import Path
from typing import Callable, Dict, Optional

import numpy as np
import xlsxwriter

from config import DATA_COLUMNS, DATA_DICTIONARY
from generator import SyntheticPowerSystemGenerator


def unique_path(path: str) -> str:
    p = Path(path)
    if not p.exists():
        return str(p)
    stem, suffix = p.stem, p.suffix
    counter = 2
    while True:
        candidate = p.with_name(f"{stem}_{counter}{suffix}")
        if not candidate.exists():
            return str(candidate)
        counter += 1


def _safe_cell(value):
    if isinstance(value, (np.floating, float)):
        if math.isnan(float(value)) or math.isinf(float(value)):
            return None
        return float(value)
    if isinstance(value, (np.integer, int)):
        return int(value)
    return value


def export_excel(
    output_path: str,
    config: Dict,
    progress_callback: Optional[Callable[[float, str], None]] = None,
    cancel_check: Optional[Callable[[], bool]] = None,
) -> str:
    """Generate a new .xlsx workbook with bounded memory usage."""
    output_path = unique_path(output_path)
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)

    generator = SyntheticPowerSystemGenerator(config)
    generator._validate()
    total_rows = int(config["rows"])

    workbook = xlsxwriter.Workbook(output_path, {"constant_memory": True, "nan_inf_to_errors": True})
    try:
        header_fmt = workbook.add_format({"bold": True, "bg_color": "#D9EAF7", "border": 1})
        note_fmt = workbook.add_format({"text_wrap": True, "valign": "top"})
        warning_fmt = workbook.add_format({"bold": True, "bg_color": "#FFF2CC", "text_wrap": True})
        pct_fmt = workbook.add_format({"num_format": "0.00"})

        # Main dataset sheet.
        ws = workbook.add_worksheet("Dataset")
        ws.freeze_panes(1, 3)
        for col_idx, name in enumerate(DATA_COLUMNS):
            ws.write(0, col_idx, name, header_fmt)
        ws.set_column(0, 1, 15)
        ws.set_column(2, 2, 12)
        ws.set_column(3, 13, 14)
        ws.set_column(14, len(DATA_COLUMNS) - 1, 18)

        excel_row = 1
        last_report = 0
        for global_start, chunk in generator.iter_chunks(chunk_size=20_000):
            if cancel_check and cancel_check():
                raise RuntimeError("Generation cancelled by user.")
            n = len(chunk["time_s"])
            for i in range(n):
                row = generator.row_tuple(global_start + i, chunk, i)
                for col, value in enumerate(row):
                    safe = _safe_cell(value)
                    if safe is None:
                        ws.write_blank(excel_row, col, None)
                    else:
                        ws.write(excel_row, col, safe)
                excel_row += 1

            completed = min(global_start + n, total_rows)
            if progress_callback and (completed - last_report >= 20_000 or completed == total_rows):
                last_report = completed
                progress_callback(completed / total_rows, f"Writing dataset rows: {completed:,} / {total_rows:,}")

        # Configuration sheet.
        cfg_ws = workbook.add_worksheet("Configuration")
        cfg_ws.set_column(0, 0, 30)
        cfg_ws.set_column(1, 1, 28)
        cfg_ws.set_column(2, 2, 65)
        cfg_ws.write(0, 0, "IMPORTANT", header_fmt)
        cfg_ws.write(0, 1, "Synthetic prototype", warning_fmt)
        cfg_ws.write(
            0, 2,
            "The current electrical signals are generated by a transparent synthetic demo model. "
            "Replace the synthetic simulator with the validated laboratory/Simulink/PSCAD model before using the data as research-grade physical results.",
            warning_fmt,
        )
        cfg_ws.write_row(2, 0, ["Parameter", "Value", "Meaning"], header_fmt)
        descriptions = {
            "rows": "Requested data rows in the Dataset sheet.",
            "sampling_rate_hz": "Samples per second within each synthetic simulation run.",
            "simulation_duration_s": "Duration of each synthetic simulation run.",
            "random_seed": "Base seed for reproducible synthetic noise.",
            "natural_noise_pct": "Small baseline measurement/noise variation.",
            "load_pct": "Selected load level.",
            "power_factor": "Selected power factor.",
            "nominal_voltage_rms_v": "Demo baseline phase RMS voltage.",
            "nominal_current_rms_a": "Demo baseline phase RMS current at 100% load.",
            "frequency_hz": "Nominal frequency.",
            "vdc_v": "Demo baseline DC-link voltage.",
            "idc_a": "Demo baseline DC current at 100% load.",
            "grid_strength": "Qualitative synthetic grid-strength modifier.",
            "feeder_impedance_pu": "Synthetic feeder impedance modifier.",
            "inverter1_power_pct": "Configured inverter-1 power share/reference.",
            "inverter2_power_pct": "Configured inverter-2 power share/reference.",
        }
        r = 3
        for key, value in config.items():
            cfg_ws.write(r, 0, key)
            cfg_ws.write(r, 1, value)
            cfg_ws.write(r, 2, descriptions.get(key, "Configured application parameter."), note_fmt)
            r += 1

        # Metadata sheet.
        meta_ws = workbook.add_worksheet("Metadata")
        meta_ws.set_column(0, 0, 28)
        meta_ws.set_column(1, 1, 55)
        plan = generator.plan
        metadata = [
            ("generator", "SyntheticPowerSystemGenerator"),
            ("simulations_required", plan.simulations_required),
            ("samples_per_simulation", plan.samples_per_simulation),
            ("requested_rows", plan.requested_rows),
            ("mode", config.get("mode", "Normal")),
            ("fault_enabled", config["fault_enabled"]),
            ("cyber_enabled", config["cyber_enabled"]),
            ("communication_enabled", config["comm_enabled"]),
            ("label_rule", "Combined if fault+cyber overlap; otherwise Fault/Cyberattack/Communication/Normal."),
        ]
        meta_ws.write_row(0, 0, ["Metadata", "Value"], header_fmt)
        for idx, (k, v) in enumerate(metadata, start=1):
            meta_ws.write(idx, 0, k)
            meta_ws.write(idx, 1, v)

        # Data dictionary.
        dd_ws = workbook.add_worksheet("Data_Dictionary")
        dd_ws.set_column(0, 0, 28)
        dd_ws.set_column(1, 1, 80)
        dd_ws.write_row(0, 0, ["Column / Group", "Description"], header_fmt)
        for idx, (k, v) in enumerate(DATA_DICTIONARY.items(), start=1):
            dd_ws.write(idx, 0, k)
            dd_ws.write(idx, 1, v, note_fmt)

        # Summary sheet.
        sum_ws = workbook.add_worksheet("Summary")
        sum_ws.set_column(0, 0, 28)
        sum_ws.set_column(1, 1, 65)
        sum_ws.write_row(0, 0, ["Item", "Value"], header_fmt)
        summary = [
            ("Rows generated", total_rows),
            ("Mode", config.get("mode", "Normal")),
            ("Sampling rate (Hz)", config["sampling_rate_hz"]),
            ("Simulation duration (s)", config["simulation_duration_s"]),
            ("Synthetic simulation runs", plan.simulations_required),
            ("Fault configuration", f"{config['fault_type']} at {config['fault_location']}" if config["fault_enabled"] else "Disabled"),
            ("Cyber configuration", f"{config['cyber_type']} on {config['cyber_target']}" if config["cyber_enabled"] else "Disabled"),
            ("Communication impairment", "Enabled" if config["comm_enabled"] else "Disabled"),
        ]
        for idx, (k, v) in enumerate(summary, start=1):
            sum_ws.write(idx, 0, k)
            sum_ws.write(idx, 1, v)

        if progress_callback:
            progress_callback(1.0, "Finalizing Excel workbook...")
    except Exception:
        workbook.close()
        if os.path.exists(output_path):
            try:
                os.remove(output_path)
            except OSError:
                pass
        raise
    else:
        workbook.close()

    return output_path
